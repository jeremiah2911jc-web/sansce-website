import fs from 'node:fs';import{geographyAliases,countyRegion}from'../shared/traffic-geography.js';
const sql=`-- Source: shared/taiwan-geography-data.js (official NLSC names). Generated by this script.
-- Preserve original classified metadata; never rewrite IDs, dates, counts, paths or durations.
begin;
lock table public.sanze_site_pageviews in share row exclusive mode;
alter table public.sanze_site_pageviews add column if not exists geo_original jsonb;
alter table public.sanze_site_pageviews add column if not exists geo_resolution text;
alter table public.sanze_site_pageviews add column if not exists geo_version integer;
create or replace function public.sanze_resolve_geography(p_country text,p_county text,p_city text,p_region text)
returns table(county text,region text,resolution text) language plpgsql immutable set search_path='' as $fn$
declare
 aliases jsonb := $data$${JSON.stringify(geographyAliases)}$data$::jsonb;
 regions jsonb := $data$${JSON.stringify(countyRegion)}$data$::jsonb;
 code text:=regexp_replace(upper(coalesce(p_county,'')),'^TW-','');
 city_key text:=regexp_replace(replace(lower(coalesce(p_city,'')),'台','臺'),'[[:space:].''’_-]','','g');
 candidates jsonb; county_candidates jsonb; known text; fallback text;
begin
 known:=case when regions ? code then code end;
 if p_country is distinct from 'TW' then
  county:=null;region:=case when p_country is not null then 'overseas' when p_region in ('north','central','south','east','islands') then p_region else 'unknown' end;
  resolution:=case when p_country is not null then 'country_only' else 'unknown' end;return next;return;
 end if;
 county_candidates:=aliases->'counties'->city_key;
 candidates:=coalesce(county_candidates,aliases->'districts'->city_key);
 if candidates is not null then
  if known is not null and candidates ? known then county:=known;resolution:='consistent';
  elsif jsonb_array_length(candidates)=1 and county_candidates is null then county:=candidates->>0;resolution:=case when known is not null then 'district_corrected' else 'district_mapped' end;
  elsif jsonb_array_length(candidates)=1 and known is null then county:=candidates->>0;resolution:='city_mapped';
  else resolution:=case when known is not null then 'conflict' else 'ambiguous' end;end if;
 elsif known is not null then county:=known;resolution:='subdivision_only';
 else resolution:='unknown';end if;
 select case when count(distinct regions->>value)=1 then min(regions->>value) end into fallback from jsonb_array_elements_text(coalesce(candidates,'[]'::jsonb));
 region:=case when county is not null then regions->>county else coalesce(fallback,case when resolution='conflict' then 'taiwan_unknown' when p_region in ('north','central','south','east','islands') then p_region else 'taiwan_unknown' end) end;
 return next;
end;$fn$;
revoke all on function public.sanze_resolve_geography(text,text,text,text) from public,anon,authenticated;
grant execute on function public.sanze_resolve_geography(text,text,text,text) to service_role;
create or replace function public.sanze_normalize_geography() returns trigger language plpgsql set search_path='' as $fn$
declare g record;
begin
 if tg_op='UPDATE' and old.geo_original is not null then new.geo_original:=old.geo_original;end if;
 if new.geo_original is null then new.geo_original:=jsonb_build_object('country',new.geo_country,'county',new.geo_county,'city',new.geo_city,'region',new.geo_region);end if;
 select * into g from public.sanze_resolve_geography(new.geo_original->>'country',new.geo_original->>'county',new.geo_original->>'city',new.geo_original->>'region');
 new.geo_country:=new.geo_original->>'country';new.geo_county:=g.county;new.geo_region:=g.region;
 new.geo_city:=case when new.geo_country is not null and (new.geo_country<>'TW' or g.resolution not in ('conflict','ambiguous')) then new.geo_original->>'city' end;
 new.geo_resolution:=g.resolution;new.geo_version:=1;
 return new;
end;$fn$;
revoke all on function public.sanze_normalize_geography() from public,anon,authenticated;
drop trigger if exists sanze_normalize_geography on public.sanze_site_pageviews;
create trigger sanze_normalize_geography before insert or update of geo_country,geo_county,geo_city,geo_region,geo_original on public.sanze_site_pageviews for each row execute function public.sanze_normalize_geography();
create temp table sanze_geo_before on commit drop as select event_id,coalesce(geo_original,jsonb_build_object('country',geo_country,'county',geo_county,'city',geo_city,'region',geo_region)) original,
 to_jsonb(p)-array['geo_original','geo_resolution','geo_version','geo_country','geo_county','geo_city','geo_region'] unchanged from public.sanze_site_pageviews p;
update public.sanze_site_pageviews set geo_county=geo_county where geo_version is distinct from 1;
do $check$ begin
 if exists(select 1 from sanze_geo_before b full join public.sanze_site_pageviews p using(event_id) where b.event_id is null or p.event_id is null or b.unchanged is distinct from (to_jsonb(p)-array['geo_original','geo_resolution','geo_version','geo_country','geo_county','geo_city','geo_region']) or p.geo_original is distinct from b.original) then raise exception 'Geography correction changed non-location data';end if;
end;$check$;
commit;
`;
fs.writeFileSync('docs/traffic/geography-correction-schema.sql',sql);
