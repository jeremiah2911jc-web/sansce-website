      "換坪數字需要試算，不能用獎勵上限代替",
      "一坪換幾坪，必須先確認新舊坪數各自包含哪些面積，再把基地條件、開發成本與出資安排放進計算。舊屋主建物、新屋含公設的登記面積，代表的內容不同；分回同樣坪數，由地主另外出資，或透過分配房地支付費用，負擔也不同。把這些差異省略，倍率就失去比較基礎。\n\n容積增加可以改善重建的財務條件，但獎勵增加多少，與地主多分多少，並無固定的換算比例。依權利變換制度，更新後房地須處理共同負擔，再按更新前土地權利價值比率分配。工程、融資與管理等支出，不會因為獎勵提高就消失。[2]\n\n這次討論連法規條件都被簡化了。行政院2026年7月16日通過的草案，將符合條件的自主更新適用一般1.5倍上限，與另行無償捐贈社宅及其土地產權、經審議後最高可達2倍的規定分開處理。截至10月24日，該案仍在立法院審議階段。[3][4]\n\n把捐贈條件省去，直接寫成自主都更多了容積，再接著推估地主有機會分回1.4、1.5倍，已經改變了政策資訊的意思。捐出的房地無法留給地主分配，取得獎勵所需的支出也必須計算。缺少這些前提，讀者看到的是被放大的收益期待。\n\n媒體與評論者若要提出換坪數字，至少應交代適用基地、新舊面積、地主出資與估算假設。加上「有機會」三個字，並不能補上欠缺的計算。可能性仍需要依據，不能靠另一類案件的成果來填空。"
